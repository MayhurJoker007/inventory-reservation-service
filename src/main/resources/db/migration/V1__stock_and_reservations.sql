CREATE TABLE stock_item (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    sku         VARCHAR(64)  NOT NULL,
    warehouse   VARCHAR(32)  NOT NULL,
    on_hand     INTEGER      NOT NULL,
    reserved    INTEGER      NOT NULL DEFAULT 0,
    version     BIGINT       NOT NULL DEFAULT 0,
    CONSTRAINT uq_stock_sku_warehouse UNIQUE (sku, warehouse),
    -- the database refuses to oversell even if the application gets it wrong
    CONSTRAINT ck_stock_reserved CHECK (reserved >= 0 AND reserved <= on_hand),
    CONSTRAINT ck_stock_on_hand CHECK (on_hand >= 0)
);

CREATE TABLE reservation (
    id               UUID         PRIMARY KEY,
    idempotency_key  VARCHAR(100) NOT NULL,
    order_ref        VARCHAR(64)  NOT NULL,
    status           VARCHAR(16)  NOT NULL,
    created_at       TIMESTAMP    NOT NULL,
    expires_at       TIMESTAMP    NOT NULL,
    closed_at        TIMESTAMP,
    CONSTRAINT uq_reservation_idempotency UNIQUE (idempotency_key)
);
CREATE INDEX ix_reservation_held_expiry ON reservation (status, expires_at);

CREATE TABLE reservation_line (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    reservation_id  UUID    NOT NULL REFERENCES reservation (id),
    stock_item_id   BIGINT  NOT NULL REFERENCES stock_item (id),
    quantity        INTEGER NOT NULL CHECK (quantity > 0)
);
